"""Write the Excel template of each type of architectural decision (X-1) in Templates/, from the fields of its sheet
in ATLAS (model.schema), with the layout of the documents generated by ATLAS (arcadia_tool.documents).

    .venv/Scripts/python.exe scripts/make_adr_templates.py

Run it again whenever the fields of a type change (tests/test_adr_templates.py checks the files are up to date)."""
import sys
import unicodedata
from datetime import date
from pathlib import Path

from openpyxl import Workbook

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from arcadia_tool.documents.adr import STATUSES, WHO, WIDTHS, write_adr  # noqa: E402
from arcadia_tool.documents.layout import FIRST_ROW, SheetWriter  # noqa: E402,F401  (FIRST_ROW: for the tests)
from arcadia_tool.documents.sa import BASELINE, Doc  # noqa: E402
from arcadia_tool.model.schema import ADR_AREAS, ADR_TYPES  # noqa: E402

TEMPLATES = ROOT / "Templates"
VERSION = "1.1"


def file_name(adr_type):
    """Template_X-1.nn_ADR_<tipo>.xlsx, numbered in the order of the areas (as in the window of the types)."""
    order = [t for _, types in ADR_AREAS for t in types]
    ascii_name = unicodedata.normalize("NFKD", adr_type).encode("ascii", "ignore").decode()
    words = "".join(c if c.isalnum() else " " for c in ascii_name).split()
    return f"Template_X-1.{order.index(adr_type) + 1:02d}_ADR_{'_'.join(words)}.xlsx"


def line():
    return (f"Template ARCADIA per i team di sviluppo · v{VERSION} · {date.today():%d/%m/%Y} · Baseline delle "
            f"specifiche: {BASELINE} · {WHO}")


def make(adr_type, _when=None):
    book = Workbook()
    ws = book.active
    ws.title = "X-1"
    write_adr(ws, Doc(filled=False, date=f"{date.today():%d/%m/%Y}"), adr_type, None, line())
    book.properties.title = f"X-1 · {adr_type} · template ARCADIA"
    path = TEMPLATES / file_name(adr_type)
    book.save(path)
    return path


REGISTER = "Template_X-1.00_Registro_ADR_aperte.xlsx"
REGISTER_COLUMNS = ("ID dell'ADR", "Breve descrizione", "Team proponente", "Stato")


def make_register(rows=25):
    """The list of the open ADR: those not yet decided by the Design Authority (see storage.adr_register, which
    writes it filled in from the project)."""
    book = Workbook()
    ws = book.active
    ws.title = "X-1"
    w = SheetWriter(ws, WIDTHS)
    w.intro("X-1 · Registro delle decisioni architetturali (ADR) aperte", line(),
            "Tenere sotto controllo le ADR proposte e non ancora decise dalla Design Authority.",
            "Una riga per ADR aperta: l'ID e il titolo della sua scheda, il team che l'ha proposta e lo stato. Quando "
            "la Design Authority decide, l'ADR esce dal registro. In ATLAS lo stesso elenco, già compilato dal "
            "progetto, si ottiene con «Esporta ADR aperte…» nell'elenco X-1 o con «Genera documentazione».")
    w.document({"Template": ("X-1", False), "Team / dominio": ("es. T5 · DF07, DF08", True),
                "Versione": ("es. 0.1", True), "Data": ("gg/mm/aaaa", True),
                "Stato": ("Bozza / In revisione / Approvato", True), "Baseline SRS": ("SUBSET-026 v3.6.0", False)})
    w.table([(REGISTER_COLUMNS[0], 1, ()), (REGISTER_COLUMNS[1], 3, ()), (REGISTER_COLUMNS[2], 1, ()),
             (REGISTER_COLUMNS[3], 1, STATUSES)],
            example=["ADR-nnn", "Titolo della decisione", "es. T5 · Odometria", "Proposta"], empty=rows,
            label="ADR aperte")
    w.finish()
    book.properties.title = "X-1 · Registro delle ADR aperte · template ARCADIA"
    path = TEMPLATES / REGISTER
    book.save(path)
    return path


def main():
    # The register is written once, then kept as it is edited by hand («--register» writes it again).
    if "--register" in sys.argv or not (TEMPLATES / REGISTER).exists():
        print(make_register().name)
    for adr_type, _when in ADR_TYPES:
        print(make(adr_type).name)


if __name__ == "__main__":
    main()
