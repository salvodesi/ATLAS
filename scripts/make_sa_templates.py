"""Write the Excel templates of the SA phases (SA-1 … SA-7) in Templates/, from the fields of their sheets in ATLAS
(model.schema), with the layout of the documents generated by ATLAS (arcadia_tool.documents.sa).

    .venv/Scripts/python.exe scripts/make_sa_templates.py

Run it again whenever the fields of a sheet change (tests/test_documentation.py checks the files are up to date)."""
import sys
from datetime import date
from pathlib import Path

from openpyxl import Workbook

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from arcadia_tool.documents.sa import ARTIFACTS, Doc, write_sheet  # noqa: E402

TEMPLATES = ROOT / "Templates"


def make(artifact):
    book = Workbook()
    ws = book.active
    ws.title = artifact.code
    write_sheet(ws, Doc(filled=False, date=f"{date.today():%d/%m/%Y}"), artifact, None)
    book.properties.title = f"{artifact.code} · {artifact.title} · template ARCADIA"
    path = TEMPLATES / artifact.template
    book.save(path)
    return path


def main():
    for artifact in ARTIFACTS:
        print(make(artifact).name)


if __name__ == "__main__":
    main()
