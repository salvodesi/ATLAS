"""The SA-2 catalogue of the system functions kept in Excel: one worksheet per domain, named after its ID (DF01),
with a row of headings («ID», «Nome (verbo + oggetto)», «Clausole SRS», «Componente Logico proposto», «Stato
Sezione», «Stato») and then a row per function. Read to import the functions hypothesised by the teams."""
import re
from dataclasses import dataclass, field

import openpyxl

DOMAIN_SHEET = re.compile(r"^DF\d+$", re.IGNORECASE)
HEADINGS = {"id": "id", "nome (verbo + oggetto)": "name", "nome": "name", "clausole srs": "clauses",
            "componente logico proposto": "component", "stato sezione": "origin", "stato": "status",
            # The catalogue generated by ATLAS («Genera documentazione»): its sections, «Funzione nuova» Sì / No.
            "sezioni srs": "clauses", "funzione nuova": "new"}


@dataclass
class CatalogueFunction:
    sheet: str  # the worksheet: the ID of its domain (DF01)
    row: int
    ident: str  # its ID in the workbook (not kept: ATLAS gives its own)
    name: str
    clauses: str = ""  # as written
    origin: str = ""  # «Nuova», «Presente in Tab 4.5.2.1»
    status: str = ""
    notes: list = field(default_factory=list)  # the cells after the known columns


def _text(value):
    return " ".join(str(value).split()) if value is not None else ""


def read_function_sheets(path, sheets=None):
    """The functions with a name of every worksheet of a domain, in their order. sheets (a list): gets the IDs of
    all the worksheets of a domain, also those without functions."""
    workbook = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        result = []
        for ws in workbook.worksheets:
            if not DOMAIN_SHEET.match(ws.title.strip()):
                continue
            if sheets is not None:
                sheets.append(ws.title.strip().upper())
            columns = named = None
            for r, row in enumerate(ws.iter_rows(values_only=True), start=1):
                if columns is None:
                    if row and isinstance(row[0], str) and row[0].strip().lower() == "id":
                        columns = {c: HEADINGS[str(v).strip().lower()] for c, v in enumerate(row)
                                   if v is not None and str(v).strip().lower() in HEADINGS}
                        named = {c for c, v in enumerate(row) if _text(v)}  # the other columns: ignored
                    continue
                values = {name: row[c] if c < len(row) else None for c, name in columns.items()}
                name = _text(values.get("name"))
                if not name or not str(values.get("id") or "").strip().upper().startswith("SF"):
                    continue  # an empty row of the template, the checklist under the table
                # The notes in the margin: the cells of the columns without a heading.
                notes = [_text(v) for c, v in enumerate(row) if c not in named and _text(v)]
                origin = _text(values.get("origin")) or ("Nuova" if _text(values.get("new")).lower() == "sì" else "")
                result.append(CatalogueFunction(ws.title.strip().upper(), r, _text(values.get("id")), name,
                                                str(values.get("clauses") or "").strip(), origin,
                                                _text(values.get("status")), notes))
        return result
    finally:
        workbook.close()
